# o dicionário guarda chave e valor
aluno = {
    'nome': 'Pedro Henrique',
    'nota': 9.2,
    'ativo': True
}

# o tipo dele é dict
print(type(aluno))

# o acesso é pela chave e não por número como na lista
print(aluno['nome'])
print(aluno['nota'])
print(aluno['ativo'])

# o len conta quantos pares tem
print(len(aluno))

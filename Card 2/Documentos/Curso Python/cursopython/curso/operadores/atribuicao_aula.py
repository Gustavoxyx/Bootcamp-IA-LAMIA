# o igual guarda o valor na variável
resultado = 2
print(resultado)

# a variável pode receber outro valor depois
resultado = 3
print(resultado)

# a variável não tem tipo fixo agora ela guarda texto
resultado = 'texto'
print(resultado)

resultado = 2
# o += é atalho pra resultado igual resultado mais resultado
resultado += resultado
# agora ele soma 4 mais 3
resultado += 3
print(resultado)

# o -= subtrai e já guarda
resultado -= 1
print(resultado)

# o *= multiplica
resultado *= 4
print(resultado)

# o /= divide e o valor vira float
resultado /= 2
print(resultado)

# o %= guarda o resto da divisão
resultado %= 6
print(resultado)

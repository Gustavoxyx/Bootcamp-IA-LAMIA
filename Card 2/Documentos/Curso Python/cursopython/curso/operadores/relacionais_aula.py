x = 7
y = 5

# esses operadores sempre devolvem True ou False
# maior
print(x > y)
# maior ou igual
print(x >= y)
# menor
print(x < y)
# menor ou igual
print(x <= y)
# os dois iguais comparam valor e não podemos confundir com um igual que é atribuição
print(x == y)
# diferente
print(x != y)

# o 5 com aspas é texto e o 5 sem aspas é número então eles são diferentes
print('5' != 5)
